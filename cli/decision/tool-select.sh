#!/usr/bin/env bash
# tool-select.sh — 工具选型决策树（6 棵树的交互式走查）
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/../lib/common.sh"

MODE="interactive"

usage() {
  cat <<'EOT'
用法: tool-select.sh [--help] [--explain] [--dry-run] [--json]

按 6 棵决策树选工具：交期长 / 库存高 / 不良率高 / OEE 低 / 现场乱 / 要减人。
输出：上什么工具 + 为什么不选别的 + 它掩盖了什么。

解决什么问题:
  避免"先上工具再诊断"（拿看板当装修）。本脚本强制先分流问题类型，
  再给工具，并明确指出每个工具的默认假设与盲区。

选项:
  --help     显示本帮助
  --explain  打印 6 棵树的判据与心智模型（教学模式）
  --dry-run  走完不写文件
  --json     JSON 输出
EOT
}

explain() {
  cat <<'EOT'
【6 棵决策树的判据与来源】

通用分叉框架（第一层）：
  流不动（停滞/在制高） / 做不快（C/T 超 T/T） / 做不稳（波动/不良） / 做不动（设备/人缺）

树 1 交期长 —— 先算增值比区分「停滞型」与「加工型」
  增值比 <5%（启发式基线，非通用阈值）→ 停滞型 → 画物与情报流程图找最长停滞段
    · 情报前置占比 >50% → 生产计划三层 + 拉动式计划（**不是先上设备**）
    · 在制三角高、超市爆 → 单件流/单元 + 看板拉动（**不是先压加工速度**）
  增值比正常但各工序 C/T > T/T → 加工型 → 才谈 SMED / 线平衡
    · 换型占工序时间 >30% → 上 SMED 而非线平衡（**换型会打碎平衡**）
  来源: research/02-tools.md §2树 1

树 2 库存高 —— 库存是结果不是原因，先问"哪种因"
  换型因 → 先 SMED 缩批量再降库存（直接砍库存会断线）
  波动因（推动排产）→ 平准化 + 看板（没平准硬拉 = 看板变噪声放大器）
  外部因（供应商不稳）→ 先治供应链，**此时上内部看板无效**

树 3 不良率高 —— 三道关依次过
  ①稳不稳（管制图有异常点 → 先稳，此时谈 Cpk 无意义）
  ②流没流出（流出 → 自工序完结/防呆/安灯，不是加终端检验）
  ③标准执不执行（执行 → 日常管理/OJT，**不是上 6σ**）

树 4 OEE 低 —— 先拆三率，别笼统"抓设备"
  时间稼动低 → 自主保全（不是加操作工）
  性能低（微停未记录）→ 先数据采集暴露微停，再个别改善
  良品率低（设备致不良）→ 计划保全 + 精度/夹具
  注：Nakajima 的 85% 是**拉伸目标**（0.90×0.95×0.99），行业典型约 60%，
      连续流程业常 >90%。**不可当通用硬标准。**

树 5 现场乱 —— 有标准不维持 vs 根本没标准
  连"要/不要"都分不清 → 5S 整理先行（红牌作战）
  标准有但乱 → 定置 + 目视 + 红牌
  **判据：红牌作战后一个月回潮 = 无 SDCA 维持机制，5S 必反弹**

树 6 要减人 —— 真效率 vs 假效率
  真效率低（有过量生产/等待）→ 少人化：用更少人做刚好的量
  假效率（C/T≈T/T已满负荷）→ 先改善，直接裁人 = 把人累坏
  **判据：「人均产出高但库存也高」= 假效率，减人无效甚至有害**
  术语：目标是**少人化**（弹性），不是**省人化**（减人头）

共同纪律：
  决策树分叉数字均为[推断]级启发式基线，**先量再定**，不可作通用阈值。
  来源: research/02-tools.md §2、§3
EOT
}

recommend() {
  local scene="$1"
  case "$scene" in
    1) cat <<'EOT'
推荐路径:
  1) 先算增值比 = 增值时间 / L/T
  2) 增值比低（停滞型）→ 画物与情报流程图，锁定最长停滞段
     · 情报前置占比 >50% → 生产计划三层 + 拉动式计划
     · 在制三角高、超市爆 → 单件流/单元 + 看板拉动
  3) 增值比正常但 C/T > T/T（加工型）→ 才谈SMED / 线平衡
     · 换型占比 >30% → 上 SMED 而非线平衡

不推荐:
  ✗ 停滞型却先买设备 → 加工速度不是瓶颈，买了更浪费
  ✗ 停滞型却先压加工速度 → 机会在队列不在机器
  ✗ 加工型却只做 VSM不碰换型 → 图很漂亮，损失照旧

组合顺序: VSM现状 → 未来状态 → 拉动（顺序反了 = 盲拉）
加载分册: lean-system.md / jit.md / supply-chain.md
EOT
      ;;
    2) cat <<'EOT'
推荐路径:
  1) 先问"库存是哪种因"
     · 换型时间长 → 大批量是被迫 → 先 SMED 缩批量（治本），再降库存
     · 需求波动大 + 推动排产 → 平准化 + 看板拉动
     · 超市水位持续 > 补货点 → 看板张数/补货规则设错或 FIFO 失效
     · 原材料库存高 + 供应商准时率低 → 先治供应链（此时上内部看板无效）

不推荐:
  ✗ 直接砍库存而不压换型 → 断线（不是治本）
  ✗ 没平准就硬拉看板 → 波动冲垮上游，看板变噪声放大器
  ✗ 套张数公式定库存而不做需求波动分析 → 缺料与积压双现

组合顺序: SMED → 平准化 → 看板 → 降库存
加载分册: jit.md / supply-chain.md
EOT
      ;;
    3) cat <<'EOT'
推荐路径（三道关，依次过）:
  1) 稳不稳？管制图有异常点/趋势 → 先稳（找特殊原因），**此时谈 Cpk/6σ 无意义**
  2) 稳定但能力不足（Cpk 低，汽车行业常取 ≥1.33）→ 设备/工艺改进，不是检验能救
  3) 流没流出？
     · 流出到客户 → 自工序完结 + 防呆 + 安灯（**不是加终端检验**）
     · 线内检出 → 标准作业 / 工序能力
  4) 标准存在但人没照做 → 日常管理 / OJT（SDCA，**不是上 6σ**）

不推荐:
  ✗ 过程不稳定时算 Cpk → 数据没稳态，数字无意义
  ✗ 用 6σ 大项目治"标准都没执行" → 维持问题当改善问题治
  ✗ 加终端检验兜底 → 与"质量源于源头"相悖

组合顺序: 源流质量/自工序完结 → 削减检验
加载分册: quality-management.md / qc-seven-tools-old.md / jidoka.md
EOT
      ;;
    4) cat <<'EOT'
推荐路径:
  1) 先拆 OEE 三率，别笼统"抓设备"
  2) 时间稼动低（停机/换型）→ 自主保全（清紧固）+ 计划保全
     · 重复故障 → 计划保全 + 备件管理（不是加操作工）
  3) 性能低（微停/降速）→ **先数据采集暴露微停**，再个别改善
     （不上采集，微停隐形，改善无从下手）
  4) 良品率低（设备致不良）→ 精度/夹具 + 计划保全 + 质量

不推荐:
  ✗ 直接考核个人 OEE → 诱发瞒微停、抢产，与"异常要停"相悖
  ✗ 性能低时直接上改善 → 微停没被记录，改了也不知道改哪

组合顺序: TPM 自主保全 → 计划保全
加载分册: tpm-equipment.md
EOT
      ;;
    5) cat <<'EOT'
推荐路径:
  1) 先判"有标准不维持" vs "根本没标准"
     · 连"要/不要"都分不清 → 5S 整理先行（红牌作战）
     · 标准有但乱 → 定置管理 + 目视化 + 红牌
  2) 细分：物品没定位 → 5S/定置；状态看不清 → 目视/安灯/管理板
  3) 配维持机制：日常管理 + 点检

不推荐:
  ✗ 只做季度大扫除 → 不建维持机制，**一个月回潮**
  ✗ 没整理就目视化 → 在垃圾上贴标签
  ✗ 板子无人更新 → 必然过期

**关键判据：红牌作战后一个月又回潮 → 说明无 SDCA 维持机制，必须补日常管理。**

组合顺序: 5S/定置 → 目视化 → 日常管理
加载分册: hoshin-daily-5s.md / shopfloor-teams.md
EOT
      ;;
    6) cat <<'EOT'
推荐路径:
  1) 先判真效率 vs 假效率
     · 真效率低（有过量生产/等待/库存）→ 少人化：用更少人做刚好的量
     · 假效率（C/T≈T/T已满负荷）→ 先改善，直接减人 = 把人累坏
  2) 细分：编成效率低（行业常见目标 ≥90%）→ 线平衡/山积图
     · 换型频繁 → SMED
     · 工序间不能互替 → 多能工/OJT

不推荐:
  ✗ 直接裁人 → 断线/质量崩（不是真改善）
  ✗ 把"人均产出提升"当成果 → 可能是加班堆出来的假效率
  ✗ 把"省人化"当"少人化" → 省人化=减人头（牺牲弹性），少人化=弹性

**关键判据：「人均产出高但库存也高」= 假效率，减人无效甚至有害。**

⚠️ 纪律：精益改善不得用作裁员工具。改善一做完就裁人，会导致后续改善无人敢提
   （实证研究已在印度汽车业观察到此现象）。

组合顺序: 消除浪费 → 少人化（不是砍人头）
加载分册: jidoka.md / jit.md / rollout-talent.md
EOT
      ;;
  esac
}

run() {
  h1 "工具选型决策树"
  dim "纪律：先分流问题类型，再选工具。工具是對症的药，不诊断就开药治不到根。"

  h2 "起手场景（选一个）"
  cat <<'EOT'
  1) 交期长 / 订单延期
  2) 库存高 / 资金周转慢
  3) 不良率高 / 客户抱怨
  4) 设备故障多 / OEE 低
  5) 现场乱 / 管理混乱
  6) 人工成本压力 / 要减人
EOT
  ask scene "场景编号" "1"
  case "$scene" in
    1|2|3|4|5|6) ;;
    *) warn "无效输入，按默认场景 1（交期长）处理"; scene=1 ;;
  esac

  local scene_name
  case "$scene" in
    1) scene_name="交期长/订单延期" ;;
    2) scene_name="库存高/资金周转慢" ;;
    3) scene_name="不良率高/客户抱怨" ;;
    4) scene_name="设备故障多/OEE 低" ;;
    5) scene_name="现场乱/管理混乱" ;;
    6) scene_name="人工成本压力/要减人" ;;
  esac

  # 场景 1 额外取数
  if [[ "$scene" == "1" ]]; then
    h2 "取数"
    ask vr   "增值比（增值时间/L/T，%）" ""
    ask ct   "各工序 C/T 是否 > T/T？(是/否/不确定)" ""
    ask smr  "换型占工序时间比例（%）" ""
    ask plt  "情报前置时间占总L/T 比例（%）" ""
  fi
  if [[ "$scene" == "2" ]]; then
    h2 "取数"
    ask s2_kind "库存主因自评：换型因/波动因/外部因/不确定" "不确定"
    ask s2_otd  "供应商准时交付率（%）" ""
    ask s2_sm   "换型时间（分钟）" ""
  fi
  if [[ "$scene" == "3" ]]; then
    h2 "取数"
    ask s3_stable "过程稳定吗（管制图有异常点？是/否/未判）" "未判"
    ask s3_escape "不良流到客户了吗？(是/否)" ""
    ask s3_exec  "标准存在且被执行吗？(是/否/无标准)" ""
    ask s3_cpk   "Cpk（若已知）" ""
  fi
  if [[ "$scene" == "4" ]]; then
    h2 "取数"
    ask s4_avail "时间稼动率（%）" ""
    ask s4_perf  "性能稼动率（%）" ""
    ask s4_qual  "良品率（%）" ""
  fi
  if [[ "$scene" == "5" ]]; then
    h2 "取数"
    ask s5_std   "有标准吗？(有/无/部分)" ""
    ask s5_back  "上次红牌/5S 后是否回潮？(是/否/未做过)" ""
  fi
  if [[ "$scene" == "6" ]]; then
    h2 "取数"
    ask s6_ct    "C/T 与 T/T 关系（CT≈TT满负荷 / CT<TT有余）" ""
    ask s6_wip   "当前在制品高吗？(高/低)" ""
    ask s6_eff   "线平衡编成效率（%）" ""
  fi

  h1 "推荐路径 · $scene_name"
  recommend "$scene"
  echo

  h1 "该工具的默认假设与盲区"
  dim "用了某个工具 = 默认接受了它的假设，同时它会遮住某类真实问题。"
  cat <<'EOT'
  看板      → 假设需求可预测、信号能即时准确传递 | 掩盖：补货内容对不对
  平准化→ 假设需求可被平滑           | 掩盖：压力被推给供应商
  自働化    → 假设停机成本低于不良流出 | 掩盖：无响应配套则"停得越多越乱"
  标准作业  → 假设存在"当前最优"        | 掩盖：若当前含浪费，标准会保护浪费
  自动化    → 假设流程已足够好          | 掩盖：把错误流程高效固化
  SPC       → 假设数据稳定可测          | 掩盖：数据未分层时用对工具也得错
EOT
  echo

  h1 "外行反模式自检"
  dim "以下 25 条为外行/入门常犯。详见 research/02-tools.md §4"
  cat <<'EOT'
  1先上工具再诊断（拿看板当装修）      14 用看板数量倒推库存而不做波动分析
  2 把看板做成展示看板                  15 为 JIT 而 JIT，忽略供应商稳定性
  3 用看板硬拉却没做平准化              16 把"人均产出"提升当成果
  4 5S 做成大扫除运动                  17 把管制界限当规格界限用
  5 用 6σ 治"标准都没执行"的维持问题   18 柏拉图"其他项"过高仍下结论
  6 SMED 只做内作业不做外作业          19 上 MES/数字化前没先简化流程
  7 用 OEE 考核个人                    20 电子看板但没有信号闭环/FIFO
  8 超产被当成好事                    21 把"减少在制品"当目的本身
  9 效率改善优先于质量改善              22 方针目标 >20 项致无重点
  10 自动化当作改善                    23 改善提案只重数量不重实施
  11 一次性大项目式精益                24 把"省人化"当"少人化"
  12 顾问代替现场人员做诊断            25 用自动化/机器人解决节拍不平衡
  13 培训替代现场辅导
EOT
  echo

  local REPORT="tool-select-$(TODAY).md"
  mdbuf_reset
  mdbuf_add "# 工具选型走查"
  mdbuf_add ""
  mdbuf_add "- 日期：$(TODAY)"
  mdbuf_add "- 场景：${scene} · ${scene_name}"
  mdbuf_add "- 来源：lean-production-expert v2.0 · cli/decision/tool-select.sh"
  mdbuf_add ""
  mdbuf_add "## 推荐路径"
  mdbuf_add ""
  # 注意：不可写成 `recommend | sed | while ...`——管道里的 while 是子shell，
  # mdbuf_add 的写入会丢失。必须先用命令替换捕获到变量，再在当前 shell 逐行写入。
  local rec_out
  rec_out="$(recommend "$scene" | sed 's/^/    /')"
  local rec_line
  while IFS= read -r rec_line; do
    mdbuf_add "$rec_line"
  done <<< "$rec_out"
  mdbuf_add ""
  mdbuf_add "## 纪律"
  mdbuf_add ""
  mdbuf_add "- 决策树分叉数字为**启发式基线**，非通用阈值，先量再定。"
  mdbuf_add "- 上工具前确认前置依赖已满足，否则必然失败。"
  mdbuf_add "- 工具参数与公式见执行层分册（本文件只给选型逻辑）。"
  mdbuf_add ""
  mdbuf_add "## 诚实边界"
  mdbuf_add ""
  mdbuf_add "- 本脚本只做**选型逻辑**判断，不替代现场诊断。"
  mdbuf_add "- 诊断一个工厂必须实地走线；本脚本输出的是提问框架，不是结论。"

  if [[ "$MODE" == "json" ]]; then
    printf '{"date":"%s","scene":"%s","scene_cn":"%s"}\n' "$(TODAY)" "$(jnum "$scene")" "$(jesc "$scene_name")"
    return
  fi

  if [[ "$MODE" == "dry-run" ]]; then
    dim "[dry-run] 未写文件。去掉 --dry-run 可生成 ${REPORT}"
  else
    mdbuf_write "$REPORT"
  fi
}

case "${1:-}" in
  --help|-h)    usage ;;
  --explain)    explain ;;
  --dry-run)    MODE="dry-run"; run ;;
  --json)       MODE="json"; run ;;
  "")           run ;;
  *)err "未知参数：$1"; echo; usage; exit 1 ;;
esac
